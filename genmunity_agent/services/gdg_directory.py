def mask_email(email: str) -> str:
    """Mask personal email address to protect PII when browsing non-exact matches."""
    if not email or "@" not in email:
        return "(이메일 미등록)"
    local, domain = email.split("@", 1)
    if len(local) <= 2:
        masked_local = local[0] + "***"
    elif len(local) <= 5:
        masked_local = local[:2] + "***"
    else:
        masked_local = local[:2] + "****" + local[-2:]
    return f"{masked_local}@{domain}"


def is_gde_email(email: str) -> bool:
    """Return True if the email belongs to a verified Google Developer Expert (GDE)."""
    target = (email or "").strip().lower()
    if not target:
        return False
    return any(g["email"].lower() == target for g in GDG_KOREA_GDE_DIRECTORY if g.get("email"))


def find_exact_gdg_or_gde_member(
    email: Optional[str] = None,
    name: Optional[str] = None,
    slack_id: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    """
    Find a GDE or an exact-matched GDG Korea Chapter member by email, Korean/English name, or Slack ID.
    Prioritizes GDE directory entries first.
    """
    email_q = (email or "").strip().lower()
    name_q = (name or "").strip().lower()
    slack_q = (slack_id or "").strip().lower()

    for gde in GDG_KOREA_GDE_DIRECTORY:
        if email_q and gde["email"].lower() == email_q:
            return {**gde, "match_type": "GDE_EXACT", "speaker_email_eligible": True}
        if name_q and (gde["name"].lower() == name_q or gde["name_en"].lower() == name_q):
            return {**gde, "match_type": "GDE_EXACT", "speaker_email_eligible": True}
        if slack_q and gde["slack_id"].lower() == slack_q:
            return {**gde, "match_type": "GDE_EXACT", "speaker_email_eligible": True}

    for org in GDG_KOREA_CHAPTER_ORGANIZERS:
        if not org.get("email"):
            continue
        if email_q and org["email"].lower() == email_q:
            return {
                **org,
                "category": "GDG_CHAPTER_EXACT",
                "is_gde": is_gde_email(org["email"]),
                "match_type": "GDG_EXACT",
                "speaker_email_eligible": True,
            }
        if name_q and (org["name"].lower() == name_q or org["name_en"].lower() == name_q):
            return {
                **org,
                "category": "GDG_CHAPTER_EXACT",
                "is_gde": is_gde_email(org["email"]),
                "match_type": "GDG_EXACT",
                "speaker_email_eligible": True,
            }
        if slack_q and org["slack_id"] and org["slack_id"].lower() == slack_q:
            return {
                **org,
                "category": "GDG_CHAPTER_EXACT",
                "is_gde": is_gde_email(org["email"]),
                "match_type": "GDG_EXACT",
                "speaker_email_eligible": True,
            }

    return None


def validate_speaker_email_recipient(
    email: str,
    name: str = "",
    require_gde_or_exact_gdg: bool = True,
) -> Dict[str, Any]:
    """
    Enforce privacy and speaker invitation policy:
    Speaker outreach/onboarding emails may ONLY be sent to:
    1. Verified GDEs (Google Developer Experts)
    2. 100% exact-matched GDG Chapter members (matching registered email and/or exact name)
    """
    clean_email = (email or "").strip().lower()
    if not clean_email or "@" not in clean_email:
        return {
            "allowed": False,
            "reason": "유효한 이메일 주소가 아닙니다.",
            "match_type": None,
        }

    # Check GDE directory first
    for gde in GDG_KOREA_GDE_DIRECTORY:
        if gde["email"].lower() == clean_email:
            return {
                "allowed": True,
                "match_type": "GDE",
                "member": gde,
                "reason": f"검증된 {gde['role']} ({gde['name']}) 대상자입니다.",
            }

    # Check exact GDG Chapter Organizer match
    for org in GDG_KOREA_CHAPTER_ORGANIZERS:
        if org.get("email", "").lower() == clean_email:
            if name and name.strip() and name.strip().lower() not in (
                org["name"].lower(),
                org["name_en"].lower(),
            ):
                continue
            return {
                "allowed": True,
                "match_type": "GDG_EXACT_MATCH",
                "member": org,
                "reason": f"완전히 매칭된 {org['chapter']} 소속 ({org['name']}) 대상자입니다.",
            }

    if not require_gde_or_exact_gdg:
        return {"allowed": True, "match_type": "CUSTOM", "reason": "수동 지정 수신자"}

    return {
        "allowed": False,
        "match_type": None,
        "reason": (
            f"개인정보 보호 정책에 의해 발송 차단됨 ({mask_email(clean_email)}): "
            "발표자 안내 이메일은 GDE 대상자 또는 완전히 매칭되는 GDG 운영진/멤버에게만 발송할 수 있습니다."
        ),
    }


def search_gdg_gde_directory(
    query: str = "",
    only_gde: bool = False,
    unmask_exact_matches: bool = True,
) -> Dict[str, Any]:
    """
    Search GDE Directory and GDG Korea Chapter Organizers with strict PII protection.
    - GDE matches and 100% exact-matched GDG members expose full email only when eligible for speaker contact.
    - Non-exact GDG browsing results automatically mask email addresses (`mask_email`).
    """
    q = (query or "").strip().lower()
    tokens = [t for t in q.replace(",", " ").split() if len(t) >= 2]

    gde_results: List[Dict[str, Any]] = []
    for gde in GDG_KOREA_GDE_DIRECTORY:
        haystack = f"{gde['domain']} {gde['name']} {gde['name_en']} {gde['slack_id']} {gde['affiliation']} {gde['role']}".lower()
        is_exact = bool(
            q
            and (
                q == gde["name"].lower()
                or q == gde["name_en"].lower()
                or q == gde["email"].lower()
                or q == gde["domain"].lower()
                or gde["name"].lower() in q
            )
        )
        matched = (not q) or (q in haystack) or any(tok in haystack for tok in tokens)
        if matched:
            entry = dict(gde)
            entry["masked_email"] = mask_email(gde["email"])
            entry["email"] = gde["email"] if unmask_exact_matches else mask_email(gde["email"])
            entry["exact_match"] = True
            entry["speaker_email_eligible"] = True
            gde_results.append(entry)

    gdg_exact_matches: List[Dict[str, Any]] = []
    gdg_partial_matches: List[Dict[str, Any]] = []

    if not only_gde:
        for org in GDG_KOREA_CHAPTER_ORGANIZERS:
            haystack = (
                f"{org['chapter']} {org['name']} {org['name_en']} "
                f"{org['slack_id']} {org['field']} {org['affiliation']}"
            ).lower()
            is_exact = bool(
                q
                and (
                    q == org["name"].lower()
                    or q == org["name_en"].lower()
                    or (org["slack_id"] and q == org["slack_id"].lower())
                    or (org["email"] and q == org["email"].lower())
                    or (len(org["name"]) >= 2 and org["name"].lower() in q)
                )
            )
            matched = is_exact or (not q) or (q in haystack) or any(tok in haystack for tok in tokens)
            if not matched:
                continue

            entry = dict(org)
            raw_email = org.get("email", "")
            entry["masked_email"] = mask_email(raw_email)
            entry["is_gde"] = is_gde_email(raw_email)

            if is_exact or entry["is_gde"]:
                entry["exact_match"] = True
                entry["speaker_email_eligible"] = bool(raw_email)
                entry["email"] = raw_email if (unmask_exact_matches and raw_email) else mask_email(raw_email)
                gdg_exact_matches.append(entry)
            else:
                # Mask PII for general / partial directory browsing
                entry["exact_match"] = False
                entry["speaker_email_eligible"] = False
                entry["email"] = mask_email(raw_email)
                gdg_partial_matches.append(entry)

    return {
        "query": query,
        "privacy_policy": (
            "개인정보 보호 정책 적용됨: GDE 및 완전 매칭(Exact Match) GDG 대상자만 발표자 안내 이메일 발송이 허용되며, "
            "일반 챕터 목록 조회 시 개인 이메일은 마스킹(***) 처리됩니다."
        ),
        "total_gde_count": len(GDG_KOREA_GDE_DIRECTORY),
        "total_gdg_chapter_members": len(GDG_KOREA_CHAPTER_ORGANIZERS),
        "gde_matches": gde_results,
        "gdg_exact_matches": gdg_exact_matches,
        "gdg_masked_directory": gdg_partial_matches[:25],
    }
